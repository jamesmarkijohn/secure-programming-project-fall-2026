#!/bin/sh
# One-time setup: creates .env with fresh random secrets, and a key pair for
# encrypted backups. Run it once, from the repository root, before the first
#   docker compose up --build -d
#
# Requires: openssl (preinstalled on Linux and macOS; on Windows use Git Bash
# or WSL), and either age-keygen or Docker (used to run age-keygen if missing).
set -eu
cd "$(dirname "$0")"

KEY_FILE="backup-private.key"   # gitignored; needed only to RESTORE backups

if [ -f .env ] && [ "${1:-}" != "--force" ]; then
    echo ".env already exists, so nothing was changed."
    echo "To start over: docker compose down -v   (deletes all data), then ./setup.sh --force"
    exit 1
fi

command -v openssl >/dev/null 2>&1 || { echo "openssl is required but not installed." >&2; exit 1; }

# --- Backup key pair --------------------------------------------------------
# Reuse an existing key: replacing it would make earlier backups unreadable.
if [ ! -f "$KEY_FILE" ]; then
    umask 077
    if command -v age-keygen >/dev/null 2>&1; then
        age-keygen -o "$KEY_FILE" 2>/dev/null
    else
        echo "age-keygen not found; generating the backup key with Docker instead..."
        docker run --rm alpine:3.22 sh -c 'apk add --no-cache -q age >/dev/null && age-keygen' > "$KEY_FILE"
    fi
fi
BACKUP_PUBLIC_KEY=$(sed -n 's/^# public key: //p' "$KEY_FILE")
[ -n "$BACKUP_PUBLIC_KEY" ] || { echo "Could not read the public key from $KEY_FILE." >&2; exit 1; }

# --- Random secrets ---------------------------------------------------------
POSTGRES_PASSWORD=$(openssl rand -hex 24)
DJANGO_SECRET_KEY=$(openssl rand -base64 48 | tr -d '\n=+/')
# Fernet keys are 32 random bytes, URL-safe base64 encoded.
FIELD_ENCRYPTION_KEY=$(openssl rand -base64 32 | tr '+/' '-_')

umask 077   # .env readable by you only
{
    echo "# Generated by setup.sh. Contains real secrets: never commit or share this file."
    sed -e '/^# Template only/d' -e '/^# (never committed)/d' \
        -e "s|^POSTGRES_PASSWORD=.*|POSTGRES_PASSWORD=$POSTGRES_PASSWORD|" \
        -e "s|^DJANGO_SECRET_KEY=.*|DJANGO_SECRET_KEY=$DJANGO_SECRET_KEY|" \
        -e "s|^FIELD_ENCRYPTION_KEY=.*|FIELD_ENCRYPTION_KEY=$FIELD_ENCRYPTION_KEY|" \
        -e "s|^BACKUP_PUBLIC_KEY=.*|BACKUP_PUBLIC_KEY=$BACKUP_PUBLIC_KEY|" \
        .env.example
} > .env

echo "Created .env and $KEY_FILE."
echo "Keep $KEY_FILE somewhere safe: it is the only way to restore a backup."
echo "Next: docker compose up --build -d"